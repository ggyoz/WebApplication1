CREATE OR REPLACE PROCEDURE SP_REQ_UPDATE (
    P_REQID             IN TB_REQ_INFO.REQID%TYPE,
    P_PARENTID          IN TB_REQ_INFO.PARENTID%TYPE,
    P_TITLE             IN TB_REQ_INFO.TITLE%TYPE,
    P_CONTENTS_HTML     IN CLOB,
    P_CONTENTS_TEXT     IN CLOB,
    P_REQDATE           IN TB_REQ_INFO.REQDATE%TYPE,
    P_DUEDATE           IN TB_REQ_INFO.DUEDATE%TYPE,
    P_EXPECTDATE        IN TB_REQ_INFO.EXPECTDATE%TYPE,
    P_STARTDATE         IN TB_REQ_INFO.STARTDATE%TYPE,
    P_ENDDATE           IN TB_REQ_INFO.ENDDATE%TYPE,
    P_REQTYPE           IN TB_REQ_INFO.REQTYPE%TYPE,
    P_SYSTEMCD          IN TB_REQ_INFO.SYSTEMCD%TYPE,
    P_REQMENU           IN TB_REQ_INFO.REQMENU%TYPE,
    P_REQMENU_ETC       IN TB_REQ_INFO.REQMENU_ETC%TYPE,
    P_BXTID             IN TB_REQ_INFO.BXTID%TYPE,
    P_REQTCODE          IN TB_REQ_INFO.REQTCODE%TYPE,
    P_REQUSERID         IN TB_REQ_INFO.REQUSERID%TYPE,
    P_RESUSERID         IN TB_REQ_INFO.RESUSERID%TYPE,
    P_IMPTCD            IN TB_REQ_INFO.IMPTCD%TYPE,
    P_DFCLTCD           IN TB_REQ_INFO.DFCLTCD%TYPE,
    P_PRIORITYCD        IN TB_REQ_INFO.PRIORITYCD%TYPE,
    P_MAN_DAY           IN TB_REQ_INFO.MAN_DAY%TYPE,
    P_PROC_STATUS       IN TB_REQ_INFO.PROC_STATUS%TYPE,
    P_PROC_RATE         IN TB_REQ_INFO.PROC_RATE%TYPE,
    P_ANSWER_HTML       IN CLOB,
    P_ANSWER_TEXT       IN CLOB,
    P_DELAYREASON_HTML  IN CLOB,
    P_DELAYREASON_TEXT  IN CLOB,
    P_CORCD             IN TB_REQ_INFO.CORCD%TYPE,
    P_DEPTCD            IN TB_REQ_INFO.DEPTCD%TYPE,
    P_OFFICECD          IN TB_REQ_INFO.OFFICECD%TYPE,
    P_TEAMCD            IN TB_REQ_INFO.TEAMCD%TYPE,
    P_NOTE_HTML         IN CLOB,
    P_NOTE_TEXT         IN CLOB,
    P_UPDATE_USERID     IN TB_REQ_INFO.UPDATE_USERID%TYPE
)
IS
BEGIN
    UPDATE TB_REQ_INFO SET
        PARENTID = P_PARENTID,
        TITLE = P_TITLE,
        CONTENTS_HTML = P_CONTENTS_HTML,
        CONTENTS_TEXT = P_CONTENTS_TEXT,
        REQDATE = P_REQDATE,
        DUEDATE = P_DUEDATE,
        EXPECTDATE = P_EXPECTDATE,
        STARTDATE = P_STARTDATE,
        ENDDATE = P_ENDDATE,
        REQTYPE = P_REQTYPE,
        SYSTEMCD = P_SYSTEMCD,
        REQMENU = P_REQMENU,
        REQMENU_ETC = P_REQMENU_ETC,
        BXTID = P_BXTID,
        REQTCODE = P_REQTCODE,
        REQUSERID = P_REQUSERID,
        RESUSERID = P_RESUSERID,
        IMPTCD = P_IMPTCD,
        DFCLTCD = P_DFCLTCD,
        PRIORITYCD = P_PRIORITYCD,
        MAN_DAY = P_MAN_DAY,
        PROC_STATUS = P_PROC_STATUS,
        PROC_RATE = P_PROC_RATE,
        ANSWER_HTML = P_ANSWER_HTML,
        ANSWER_TEXT = P_ANSWER_TEXT,
        DELAYREASON_HTML = P_DELAYREASON_HTML,
        DELAYREASON_TEXT = P_DELAYREASON_TEXT,
        CORCD = P_CORCD,
        DEPTCD = P_DEPTCD,
        OFFICECD = P_OFFICECD,
        TEAMCD = P_TEAMCD,
        NOTE_HTML = P_NOTE_HTML,
        NOTE_TEXT = P_NOTE_TEXT,
        UPDATE_DATE = SYSDATE, -- Use SYSDATE in DB
        UPDATE_USERID = P_UPDATE_USERID
    WHERE REQID = P_REQID;
END;
